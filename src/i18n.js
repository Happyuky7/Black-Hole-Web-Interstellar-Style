const STORAGE_KEY = 'gargantua-lang';
const listeners = new Set();

function detect(){
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if(saved && dict[saved]) return saved;
  } catch {}
  for(const pref of navigator.languages || [navigator.language || 'en']){
    if(dict[pref]) return pref;
    const base = pref.split('-')[0];
    if(base === 'zh') return 'zh-CN';
    if(base === 'pt') return 'pt-BR';
    if(dict[base]) return base;
  }
  return 'en';
}

let current = detect();
document.documentElement.lang = current;

export function getLang(){ return current; }

export function setLang(lang){
  if(!dict[lang] || lang === current) return;
  current = lang;
  document.documentElement.lang = lang;
  try { localStorage.setItem(STORAGE_KEY, lang); } catch {}
  applyI18n();
  for(const fn of listeners) fn(lang);
}

export function onLangChange(fn){ listeners.add(fn); return () => listeners.delete(fn); }

/** Translate a key; falls back to English, then to the key itself. */
export function t(key, vars){
  let s = dict[current][key] ?? dict.en[key] ?? key;
  if(vars) s = s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? `{${k}}`);
  return s;
}

/** Relabel every element under root carrying data-i18n / data-i18n-html / data-i18n-title. */
export function applyI18n(root = document){
  root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-html]').forEach(el => { el.innerHTML = t(el.dataset.i18nHtml); });
  root.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.title = t(el.dataset.i18nTitle);
    el.setAttribute('aria-label', el.title);
  });
}

/** A <select> listing every language, kept in sync with the current one. */
export function languageSelect(className = ''){
  const sel = document.createElement('select');
  sel.className = className;
  sel.setAttribute('aria-label', 'Language');
  for(const [code, name] of LANGS){
    const o = document.createElement('option');
    o.value = code; o.textContent = name;
    sel.appendChild(o);
  }
  sel.value = current;
  sel.addEventListener('change', () => setLang(sel.value));
  onLangChange(lang => { sel.value = lang; });
  return sel;
}
